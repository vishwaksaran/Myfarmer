/**
 * Translate a product/content string for the given language.
 * Falls back to the original English string when no translation exists.
 */
export function translateProduct(text: string | null | undefined, lang: LangCode): string {
    if (!text) return text ?? '';
    if (lang === 'en') return text;
    return productTranslations[text]?.[lang] ?? text;
}
